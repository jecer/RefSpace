let currentLang = localStorage.getItem('refspace-lang') || 'ru';

function t(key, params = {}) {
  let text = translations[currentLang]?.[key] || translations['ru'][key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function updateUI() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName.toLowerCase() === 'input' && el.type === 'text' && el.placeholder) {
      el.placeholder = t(key);
    } else {
      el.innerHTML = t(key);
    }
  });

  const hotkeyInput = document.getElementById('click-through-hotkey');
  const hotkeyHint = document.getElementById('click-through-hint');
  if (hotkeyInput && hotkeyHint) {
    const currentHotkey = localStorage.getItem('refspace-clickthrough-hotkey') || 'F4';
    if (hotkeyInput.value === 'Нажмите клавишу...' || 
        hotkeyInput.value === t('panel.pressKey') || 
        Object.values(translations).some(lang => lang['panel.pressKey'] === hotkeyInput.value)) {
        hotkeyInput.value = t('panel.pressKey');
    }
    hotkeyHint.innerHTML = t('panel.disableHint', { key: currentHotkey });
  }
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('refspace-lang', lang);
    updateUI();
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
  }
}

document.addEventListener('DOMContentLoaded', () => {
  updateUI();
  
  const langSelector = document.getElementById('lang-selector');
  if (langSelector) {
    langSelector.value = currentLang;
    langSelector.addEventListener('change', (e) => {
      setLanguage(e.target.value);
    });
  }
});
